const DEFAULT_FILE_ICON = 57379;

/** Return the VS Code Seti file-icon glyph that best matches a workspace path. */
export function workspaceFileIconGlyph(filePath: string): string {
  const fileName = workspaceFileName(filePath).toLowerCase();
  const namedIcon = FILE_NAME_ICONS[fileName];
  if (namedIcon !== undefined) return String.fromCodePoint(namedIcon);

  let dot = fileName.indexOf(".");
  while (dot >= 0 && dot < fileName.length - 1) {
    const suffixIcon = FILE_EXTENSION_ICONS[fileName.slice(dot + 1)];
    if (suffixIcon !== undefined) return String.fromCodePoint(suffixIcon);
    dot = fileName.indexOf(".", dot + 1);
  }

  return String.fromCodePoint(DEFAULT_FILE_ICON);
}

function workspaceFileName(filePath: string): string {
  const trimmed = filePath.replace(/[\\/]+$/, "");
  const separator = Math.max(trimmed.lastIndexOf("/"), trimmed.lastIndexOf("\\"));
  return trimmed.slice(separator + 1) || filePath;
}

